"""The shipped sample portfolio must actually be exercised.

`samples/portfolio.snapshot.json` carries all ten broker CSV formats and
is the artifact a new user (or a fork) runs first — but nothing consumed
it. The end-to-end test builds its own inline synthetic portfolio, so
**five of the nine broker parsers had zero executed lines**:
`parse_usaa`, `parse_schwab`, `parse_vanguard_401k`,
`parse_apple_savings` and `parse_coinbase_pro`. Any regression in those
shipped green, and the sample could rot without anyone noticing.

This module closes both gaps at once: it pins the sample as working
input AND gives the five orphaned parsers their first coverage.

Deliberately split into two layers:

* **Parse-level tests** — fast, no pricing, no network. These are what
  actually cover the parsers, and they assert the post-parse invariants
  CLAUDE.md declares (quantity / amount / fees non-negative, direction
  encoded in the action, every action known to the catalog).
* **One end-to-end test** — proves the sample still drives a complete
  run. Slower, so there is exactly one.

Assertions are deliberately *structural* (counts, signs, membership) and
never hard-coded totals: the sample is regenerated by
`tools/build_sample_snapshot.py`, and a test that pins its arithmetic
would break on every legitimate regeneration. Structural assertions
survive that; arithmetic belongs in `test_pipeline_snapshot.py`, whose
fixture is built for it.
"""

from __future__ import annotations

from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
